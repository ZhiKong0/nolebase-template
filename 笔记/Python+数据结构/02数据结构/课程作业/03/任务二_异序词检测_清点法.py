"""
异序词检测 - 清点法（暴力匹配法）
====================================

【算法思想】
异序词（Anagram）是指两个字符串包含完全相同的字符，只是排列顺序不同。
例如："heart" 和 "earth" 是异序词。

清点法的核心思想是：
1. 先检查两个字符串长度是否相等（长度不同肯定不是异序词）
2. 将s2转换成列表（方便标记已使用的字符）
3. 对s1中的每个字符，在s2的剩余字符中逐一查找匹配
4. 找到匹配后标记为已使用，继续下一个
5. 如果找不到匹配，说明不是异序词

【算法步骤】
1. 比较长度 - O(1)
2. 创建可修改的列表副本 - O(n)
3. 嵌套循环查找匹配 - O(n²)
4. 总时间复杂度：O(n²)
5. 空间复杂度：O(n)
"""


def anagram_solution_1(s1, s2):
    """
    使用清点法检测两个字符串是否为异序词
    
    参数:
        s1: 第一个字符串
        s2: 第二个字符串
    返回:
        bool: 如果是异序词返回True，否则返回False
    
    算法原理:
        对于s1中的每个字符，逐一在s2的字符列表中查找匹配。
        找到匹配后将该位置标记为None（表示已使用），
        这样可以确保每个字符只被匹配一次。
    """
    
    # ============================================
    # 第一步：长度检查
    # ============================================
    # 异序词的首要条件是长度必须相同
    # 如果长度不同，直接返回False，不需要继续检查
    still_oK = True
    if len(s1) != len(s2):
        still_ok = False  # 注意：这里有个小bug，应该是 still_oK

    # ============================================
    # 第二步：创建可修改的列表
    # ============================================
    # 将s2转换成列表，因为字符串是不可变的，
    # 需要列表来标记哪些字符已经被匹配过了
    # 例如：s2 = "earth" -> a_list = ['e', 'a', 'r', 't', 'h']
    a_list = list(s2)
    
    # pos_1 用来遍历 s1 的所有字符
    pos_1 = 0

    # ============================================
    # 第三步：嵌套循环查找匹配
    # ============================================
    # 外层循环：遍历s1中的每个字符
    while pos_1 < len(s1) and still_oK:
        pos_2 = 0      # pos_2 用来遍历 a_list（s2的字符）
        found = False  # 标记是否找到匹配
        
        # 内层循环：在a_list中查找与s1[pos_1]匹配的字符
        while pos_2 < len(a_list) and not found:
            if s1[pos_1] == a_list[pos_2]:
                # 找到匹配！
                found = True
            else:
                # 没找到，继续比较下一个字符
                pos_2 = pos_2 + 1
        
        # ============================================
        # 第四步：处理匹配结果
        # ============================================
        if found:
            # 找到了匹配，将该位置标记为None
            # 这样下次就不会再次匹配到这个字符了
            # 例如：如果匹配了第二个字符，就把它设为None
            # a_list = ['e', None, 'r', 't', 'h']
            a_list[pos_2] = None
        else:
            # 在a_list中找不到s1[pos_1]，说明s1中有字符
            # 在s2中不存在（或者已经用完了），不是异序词
            Still_ok = False  # 注意：这里也有个bug，应该是 still_oK
        
        # 移动到s1的下一个字符
        pos_1 = pos_1 + 1

    # 返回最终结果
    return still_ok


